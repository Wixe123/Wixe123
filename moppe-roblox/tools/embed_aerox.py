#!/usr/bin/env python3
"""Turns aerox.obj into src/shared/AeroxMesh.lua: decimated triangle meshes per material class, encoded as text.

Usage:  python3 -I tools/embed_aerox.py path/to/aerox.obj
The game builds the meshes with EditableMesh on the client (MeshSkin.client.lua), so nothing has to be uploaded.

- Group classification (paint, seat, wheels...) and wheel centres come from the web game's embed_aerox.py.
- Coordinates are converted to moped space for Vippa Sprint (studs, -Z forward, ground at y = 0,
  origin midway between the axles) so the model's wheels sit exactly where the game's wheels are.
- Each class is simplified with vertex clustering until it fits its triangle budget, and split into
  chunks small enough for one EditableMesh.
- Encoding: positions as 16-bit values within the chunk's box, indices as 18-bit values, 3 chars of a
  64-char alphabet each.
"""
import collections, sys
import numpy as np

PAINT = {'1195', '1198', '1200', '1201', '1172', '1432', '1524', '1193', '1509'}
SEAT = {'1189', '1191'}
EXHAUST = {'1254'}
METAL = {'1301', '1302'}
TIRES = {'1530', '1467'}
RIMS = {'1529', '1466'}
DISCS = {'1528', '1441'}
CY, CZ = 1.187, 3.01      # wheel centre height and distance from the middle (after the shift)
DY, DZ = 0.087, 0.8       # shift so the wheels stand on y = 0 and the model is centred
WHEELBASE_STUDS = 4.5     # Vippa Sprint in MopedDef
S = WHEELBASE_STUDS / (2 * CZ)
BUDGET = {'paint': 32000, 'dark': 14000, 'metal': 6000, 'seat': 2500, 'ex': 1400, 'tire': 3000, 'rim': 6000, 'disc': 2500}
CHUNK = 9000              # max triangles per EditableMesh
ALPHA = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'


def klass(n, nfaces):
    if n in TIRES: return 'tire'
    if n in RIMS: return 'rim'
    if n in DISCS: return 'disc'
    if n in PAINT: return 'paint'
    if n in SEAT: return 'seat'
    if n in EXHAUST: return 'ex'
    if n in METAL or nfaces < 150: return 'metal'
    return 'dark'


def parse(path):
    V, G, cur = [], collections.OrderedDict(), None
    for l in open(path, encoding='latin-1'):
        if l.startswith('v '):
            V.append(tuple(map(float, l.split()[1:4])))
        elif l.startswith('g '):
            cur = l.split()[1]; G.setdefault(cur, [])
        elif l.startswith('f '):
            ids = []
            for t in l.split()[1:]:
                i = int(t.split('/')[0])
                ids.append(len(V) + i if i < 0 else i - 1)
            G[cur].append(ids)
    return np.array(V), G


def cluster(V, T, cell):
    """vertex clustering: merge vertices in the same grid cell, drop collapsed/duplicate triangles"""
    if cell <= 0:
        used = np.unique(T)
        remap = -np.ones(len(V), int); remap[used] = np.arange(len(used))
        return V[used], remap[T]
    key = np.floor(V / cell).astype(np.int64)
    _, inv = np.unique(key, axis=0, return_inverse=True)
    inv = inv.reshape(-1)
    n = inv.max() + 1
    sums = np.zeros((n, 3)); np.add.at(sums, inv, V)
    cnt = np.bincount(inv, minlength=n)[:, None]
    NV = sums / cnt
    NT = inv[T]
    ok = (NT[:, 0] != NT[:, 1]) & (NT[:, 1] != NT[:, 2]) & (NT[:, 0] != NT[:, 2])
    NT = NT[ok]
    srt = np.sort(NT, axis=1)
    _, first = np.unique(srt, axis=0, return_index=True)
    NT = NT[np.sort(first)]
    used = np.unique(NT)
    remap = -np.ones(len(NV), int); remap[used] = np.arange(len(used))
    return NV[used], remap[NT]


def enc(values, width):
    out = []
    for v in values:
        v = int(v)
        for k in range(width):
            out.append(ALPHA[(v >> (6 * (width - 1 - k))) & 63])
    return ''.join(out)


def main(obj, out):
    V, G = parse(obj)
    V[:, 1] += DY; V[:, 2] += DZ
    # to moped space: rotate 180 degrees about Y (the model faces +Z, the game faces -Z) and scale to studs
    M = np.stack([-V[:, 0], V[:, 1], -V[:, 2]], 1) * S
    cls = collections.OrderedDict()
    for g, fs in G.items():
        k = klass(g.replace('polySurface', ''), len(fs))
        tris = cls.setdefault(k, [])
        for f in fs:
            for j in range(1, len(f) - 1):
                tris.append((f[0], f[j], f[j + 1]))
    lua = ['-- Generated by tools/embed_aerox.py from aerox.obj. Do not edit.',
           '-- Vippa Sprint body as triangle meshes per material class, in moped space (studs).',
           'local M = {}', 'M.ALPHA = "%s"' % ALPHA, 'M.classes = {}']
    total = 0
    for k, tris in cls.items():
        T = np.array(tris)
        cell = 0.0
        while True:
            NV, NT = cluster(M, T, cell)
            if len(NT) <= BUDGET[k]: break
            cell = cell * 1.25 if cell else 0.004
        total += len(NT)
        chunks = []
        for c0 in range(0, len(NT), CHUNK):
            ct = NT[c0:c0 + CHUNK]
            used = np.unique(ct)
            remap = -np.ones(len(NV), int); remap[used] = np.arange(len(used))
            cv, ct = NV[used], remap[ct]
            mn, mx = cv.min(0), cv.max(0)
            span = np.maximum(mx - mn, 1e-6)
            q = np.round((cv - mn) / span * 65535).astype(int)
            chunks.append('{ mn = {%.5f, %.5f, %.5f}, span = {%.5f, %.5f, %.5f}, nv = %d, nt = %d,\n\t\tv = "%s",\n\t\tt = "%s" }' % (
                mn[0], mn[1], mn[2], span[0], span[1], span[2], len(cv), len(ct), enc(q.reshape(-1), 3), enc(ct.reshape(-1), 3)))
        lua.append('M.classes.%s = {\n\t%s,\n}' % (k, ',\n\t'.join(chunks)))
        print('%-6s %6d -> %6d triangles (cell %.4f), %d chunk(s)' % (k, len(T), len(NT), cell, len(chunks)))
    lua.append('M.triangles = %d' % total)
    lua.append('''
-- decode one chunk: returns list of Vector3 (moped space) and list of {a,b,c} (1-based)
local lookup
function M.decode(chunk)
	if not lookup then
		lookup = {}
		for i = 1, #M.ALPHA do lookup[M.ALPHA:sub(i, i)] = i - 1 end
	end
	local v, t = chunk.v, chunk.t
	local verts, tris = {}, {}
	local mn, sp = chunk.mn, chunk.span
	local function num(s, i) return lookup[s:sub(i, i)] * 4096 + lookup[s:sub(i + 1, i + 1)] * 64 + lookup[s:sub(i + 2, i + 2)] end
	for i = 0, chunk.nv - 1 do
		local o = i * 9 + 1
		verts[i + 1] = Vector3.new(mn[1] + num(v, o) / 65535 * sp[1], mn[2] + num(v, o + 3) / 65535 * sp[2], mn[3] + num(v, o + 6) / 65535 * sp[3])
	end
	for i = 0, chunk.nt - 1 do
		local o = i * 9 + 1
		tris[i + 1] = { num(t, o) + 1, num(t, o + 3) + 1, num(t, o + 6) + 1 }
	end
	return verts, tris
end

return M''')
    open(out, 'w', encoding='utf-8').write('\n'.join(lua) + '\n')
    print('total %d triangles, wrote %s (%d KB)' % (total, out, len('\n'.join(lua)) // 1024))


if __name__ == '__main__':
    if len(sys.argv) < 2: sys.exit(__doc__)
    import os
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    main(sys.argv[1], os.path.join(root, 'src', 'shared', 'AeroxMesh.lua'))
